/** Public DSL types, engine limits, and the internal shapes shared by the parser stages. */
import type { DispatchExecutionMode } from '../../types'
import type { DiagnosticCollector } from './diagnostics.ts'

export type WorkflowDslContext = 'run' | 'task' | 'event'
export type WorkflowDiagnosticSeverity = 'error' | 'warning' | 'info' | 'hint'

export interface WorkflowDiagnostic {
  from: number
  to: number
  line: number
  severity: WorkflowDiagnosticSeverity
  message: string
}

/**
 * These limits mirror the cloud compiler and the browser queue parser. The editor deliberately
 * validates the stricter limit when the same source is accepted by one layer but rejected by the
 * next one, so a plan cannot pass the editor only to fail after orchestration.
 */
export const WORKFLOW_DSL_LIMITS = Object.freeze({
  maxPlanBytes: 2 * 1024 * 1024,
  maxRunTasks: 256,
  maxTaskEvents: 1_000,
  maxLoopItems: 1_000,
  /** Most `@for` blocks that may nest inside each other at the Run, Task and Event queue levels. */
  maxLoopNesting: 3,
  maxEventQueueBytes: 768 * 1024,
  maxExpandedPlanBytes: 32 * 1024 * 1024,
  maxQueueRepeat: 100,
  maxBrowserLoopItems: 200,
  maxBrowserTotalActs: 200,
  maxBrowserPollDepth: 3,
  maxBrowserTemplateActs: 10,
  maxExpansionIterations: 100_000,
  /** Loop iterations the Event queue check walks before it gives up. */
  maxQueueLoopWalk: 5_000,
})

/**
 * Besides its own variables, every `@for` defines these two for its body (Task, Event and queue
 * loops alike): `count` is the number of iterations; `index` is the 1-based position in a list
 * loop and repeats the value in a `range` loop. They come from the shared loop kit.
 */
export const LOOP_ALIAS_VARIABLES = Object.freeze(['index', 'count'] as const)
/** `@repeat`, `@start` and `@step` number the Acts of a body with these. */
export const REPEAT_VARIABLES = Object.freeze(['i', 'index', 'count'] as const)

/** Task variable naming the page a Task starts on; an empty value falls back to the Run's default link. */
export const START_URL_VARIABLE = 'start_url'
export const DEFAULT_START_URL = 'https://chatgpt.com/'
/** `@let` declares a variable; `@var` is the legacy spelling with the same meaning. */
export const VARIABLE_DECLARATION = /^@(?:let|var)\s+([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*?)\s*$/iu

export const SELF_URL_TOKENS = new Set(['<self>', '<current>', '<here>', '<本页>', '<当前页>', '<当前页面>'])
export const VARIABLE_TOKEN = /%([A-Za-z_][A-Za-z0-9_]*)(?::([A-Za-z0-9_]+))?%/gu
export const BACKTICK_FENCE = '```'
export const TILDE_FENCE = '~~~'

export type TemplateValue = string | number
export type TemplateVars = Record<string, TemplateValue>
export type CloudLevel = 'run' | 'task'
export type CloudBlockKind = 'task' | 'event'

export interface LineIndex {
  readonly original: string
  readonly starts: number[]
}

export interface CloudConfig {
  title: string
  executionMode: DispatchExecutionMode
  maxConcurrency: number
}

export interface CloudBlock {
  kind: CloudBlockKind
  title: string
  body: string
  line: number
}

export interface CloudLevelResult {
  config: CloudConfig
  vars: TemplateVars
  blocks: CloudBlock[]
  failed: boolean
}

export interface ParseBudget {
  expandedBytes: number
  iterations: number
}

/** Where a queue body sits: directly in the Event queue, inside an `@act`, or inside a `@for`. */
export type QueueContainer = 'queue' | 'act' | 'for'

/** One Act the browser will run, as far as the editor can tell without a page. */
export interface ActPreview {
  /** The Act's own `@event=` title, variables filled in; '' when it uses the Event title. */
  title: string
  /** First message, variables filled in; '' when the Act only navigates or waits. */
  text: string
  /** Messages and polling groups the Act sends. */
  messages: number
  /** Executor nodes (messages, links, waits, polling repeats), as Run progress counts them. */
  nodes: number
}

/** An Event as orchestration will create it, with the Acts its queue expands to. */
export interface EventPreview {
  taskTitle: string
  title: string
  /** Line of the `@event` header in the source; Events generated by one loop share it. */
  line: number
  acts: ActPreview[]
  /** Total Acts; `acts` stops at {@link WORKFLOW_DSL_LIMITS.maxBrowserTotalActs}. */
  actCount: number
}

export interface QueueBudget {
  acts: number
  /** Loop iterations walked so far; dependent loops are walked with real values. */
  walked: number
  exceeded?: boolean
}

/** Directives that the browser copies from a body into the Acts it produces. */
export interface ActDirectives {
  event?: string | undefined
  repeat?: number | undefined
  start?: number | undefined
  step?: number | undefined
}

export interface QueueValidationOptions {
  eventTitle: string
  line: number
  collector: DiagnosticCollector
  /** Variable names usable in templates. */
  activeVariables?: Set<string>
  /** Values in scope: loop bindings and `@let` declarations of the queue. */
  vars?: TemplateVars
  pollDepth?: number
  budget?: QueueBudget
  container?: QueueContainer
  /** Names bound by the enclosing `@for` blocks, innermost last. */
  loopNames?: readonly string[]
  /** Number of enclosing `@for` blocks. */
  loopDepth?: number
  /** Directives the body starts with before its own (an `@act` inherits its body's). */
  inherited?: ActDirectives
  /** Receives one entry per Act when the caller wants a preview. */
  previews?: ActPreview[] | undefined
}
